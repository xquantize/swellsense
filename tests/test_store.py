import hashlib
from datetime import UTC, datetime, timedelta, timezone

import pytest
from pydantic import ValidationError

from swellsense.ingest.models import RawDocument
from swellsense.ingest.store import load_all, save, slugify

_TEXT = "A swell is a series of waves."


def test_slugify_collapses_punctuation_and_case():
    assert slugify("Swell (ocean)") == "swell_ocean"


def test_slugify_strips_edges_and_keeps_words():
    assert slugify("Surfboard") == "surfboard"
    assert slugify("  Rip   current! ") == "rip_current"
    assert slugify("---Tide---") == "tide"


def _document(**overrides) -> RawDocument:
    text = overrides.pop("text", _TEXT)
    title = overrides.pop("title", "Swell (ocean)")
    source_id = overrides.pop("source_id", "wikipedia")
    values = {
        "id": f"{source_id}/{slugify(title)}",
        "source_id": source_id,
        "title": title,
        "url": "https://en.wikipedia.org/wiki/Swell_(ocean)",
        "license": "CC BY-SA 4.0",
        "attribution": "Wikipedia contributors",
        "usage": "open",
        "fetched_at": datetime(2026, 10, 14, 12, 0, tzinfo=UTC),
        "content_hash": hashlib.sha256(text.encode()).hexdigest(),
        "word_count": len(text.split()),
        "text": text,
    }
    values.update(overrides)
    return RawDocument(**values)


def test_save_and_load_round_trip(tmp_path):
    doc = _document()

    assert save(doc, tmp_path) is True

    path = tmp_path / "wikipedia" / "swell_ocean.json"
    assert path.is_file()
    assert load_all(tmp_path) == [doc]


def test_unchanged_content_is_not_rewritten(tmp_path):
    doc = _document()
    assert save(doc, tmp_path) is True
    path = tmp_path / "wikipedia" / "swell_ocean.json"
    written = path.read_bytes()
    modified = path.stat().st_mtime_ns

    later = doc.model_copy(update={"fetched_at": datetime(2026, 10, 15, tzinfo=UTC)})
    assert save(later, tmp_path) is False
    assert path.read_bytes() == written
    assert path.stat().st_mtime_ns == modified


def test_changed_content_is_rewritten(tmp_path):
    assert save(_document(), tmp_path) is True
    updated = _document(text="A longer swell arrived overnight.")

    assert save(updated, tmp_path) is True
    assert load_all(tmp_path) == [updated]


def test_load_all_reads_each_source_and_missing_root_is_empty(tmp_path):
    first = _document()
    second = _document(
        source_id="notes",
        title="Wind wave",
        url="https://example.com/wind-wave",
        text="Wind waves are generated by local wind.",
    )
    save(first, tmp_path)
    save(second, tmp_path)

    assert load_all(tmp_path) == [second, first]
    assert load_all(tmp_path / "missing") == []


def test_rejects_hash_or_word_count_that_disagrees_with_text():
    with pytest.raises(ValidationError, match="content_hash"):
        _document(content_hash="0" * 64)
    with pytest.raises(ValidationError, match="word_count"):
        _document(word_count=0)


def test_id_must_be_source_and_slug():
    with pytest.raises(ValidationError, match="wikipedia/swell_ocean"):
        _document(id="wikipedia/other")


def test_fetched_at_must_be_utc():
    with pytest.raises(ValidationError, match="UTC"):
        _document(fetched_at=datetime(2026, 10, 14, 12, 0))
    with pytest.raises(ValidationError, match="UTC"):
        _document(
            fetched_at=datetime(
                2026, 10, 14, 12, 0, tzinfo=timezone(timedelta(hours=12))
            )
        )


def test_usage_uses_the_source_labels():
    for usage in ("open", "permission", "private"):
        assert _document(usage=usage).usage == usage
    with pytest.raises(ValidationError):
        _document(usage="stolen")


def test_unreadable_file_is_replaced(tmp_path):
    doc = _document()
    path = tmp_path / "wikipedia" / "swell_ocean.json"
    path.parent.mkdir(parents=True)
    path.write_text("{not json", encoding="utf-8")

    assert save(doc, tmp_path) is True
    assert load_all(tmp_path) == [doc]


def test_title_needs_a_letter_or_number():
    with pytest.raises(ValidationError, match="letter or number"):
        _document(title="???")
